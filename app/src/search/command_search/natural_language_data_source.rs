const TRANSLATE_ITEM_BODY_TEXT: &str = "Translate into a shell command";
const NO_PROVIDER_MESSAGE: &str = "Turn on AI and add a model in Settings > AI (optional)";

/// Translates the query within command search.
#[derive(Clone, Debug)]
pub struct TranslateSearchItem;

impl SearchItem for TranslateSearchItem {
    type Action = CommandSearchItemAction;

    fn render_icon(
        &self,
        highlight_state: ItemHighlightState,
        appearance: &Appearance,
    ) -> Box<dyn Element> {
        let icon = UIIcon::AiAssistant
            .to_warpui_icon(highlight_state.main_text_fill(appearance))
            .finish();

        Container::new(
            ConstrainedBox::new(icon)
                .with_width(styles::icon_size(appearance))
                .with_height(styles::icon_size(appearance))
                .finish(),
        )
        .with_margin_right(8.)
        .finish()
    }

    fn render_item(
        &self,
        highlight_state: ItemHighlightState,
        app: &AppContext,
    ) -> Box<dyn Element> {
        let appearance = Appearance::as_ref(app);
        Text::new_inline(
            TRANSLATE_ITEM_BODY_TEXT,
            appearance.monospace_font_family(),
            appearance.monospace_font_size(),
        )
        .autosize_text(builder::MIN_FONT_SIZE)
        .with_color(highlight_state.main_text_fill(appearance).into_solid())
        .finish()
    }

    fn render_details(&self, _: &AppContext) -> Option<Box<dyn Element>> {
        None
    }

    fn score(&self) -> OrderedFloat<f64> {
        // A score of 0 keeps this item near, but not necessarily at, the bottom of the list.
        OrderedFloat(0.)
    }

    fn accept_result(&self) -> CommandSearchItemAction {
        CommandSearchItemAction::TranslateNaturalLanguage
    }

    fn execute_result(&self) -> CommandSearchItemAction {
        CommandSearchItemAction::TranslateNaturalLanguage
    }

    fn accessibility_label(&self) -> String {
        TRANSLATE_ITEM_BODY_TEXT.to_owned()
    }
}

/// Provides two different types of results, so it should be registered both as a sync and as an
/// async source:
/// - synchronous: a single item that translates the query when selected.
/// - asynchronous: workflows generated by the configured [`NaturalLanguageCommandProvider`].
pub struct NaturalLanguageDataSource {
    provider: Option<Arc<dyn NaturalLanguageCommandProvider>>,
    context: Option<NaturalLanguageCommandContext>,
}

impl NaturalLanguageDataSource {
    pub fn new(
        provider: Option<Arc<dyn NaturalLanguageCommandProvider>>,
        context: Option<NaturalLanguageCommandContext>,
    ) -> Self {
        Self { provider, context }
    }
}

impl SyncDataSource for NaturalLanguageDataSource {
    type Action = CommandSearchItemAction;

    fn run_query(
        &self,
        query: &Query,
        _app: &AppContext,
    ) -> Result<Vec<QueryResult<Self::Action>>, DataSourceRunErrorWrapper> {
        // When the `#` filter is applied the query is already being translated.
        if query.filters.is_empty() {
            Ok(vec![TranslateSearchItem.into()])
        } else {
            Ok(vec![])
        }
    }
}

#[cfg_attr(not(target_family = "wasm"), async_trait)]
#[cfg_attr(target_family = "wasm", async_trait(?Send))]
impl AsyncDataSource for NaturalLanguageDataSource {
    type Action = CommandSearchItemAction;

    fn run_query(
        &self,
        query: &Query,
        _app: &AppContext,
    ) -> BoxFuture<'static, Result<Vec<QueryResult<Self::Action>>, DataSourceRunErrorWrapper>> {
        let Some(provider) = self.provider.clone() else {
            return Box::pin(async {
                Err(Box::new(GenerateCommandsError::NoProvider) as Box<dyn DataSourceRunError>)
            });
        };
        let commands = provider.generate_commands(query.text.clone(), self.context.clone());

        Box::pin(async move {
            match commands.await {
                // The generated commands are ordered most plausible first; reverse them so the
                // most plausible ends up closest to the input.
                Ok(commands) => Ok(commands
                    .into_iter()
                    .map(|command| {
                        WorkflowSearchItem {
                            identity: WorkflowIdentity::Local(Box::new(WorkflowType::AIGenerated(
                                command.into(),
                            ))),
                            source: WorkflowSource::WarpAI,
                            fuzzy_matched_workflow: FuzzyMatchWorkflowResult::no_match(),
                        }
                        .into()
                    })
                    .rev()
                    .collect_vec()),
                Err(e) => Err(Box::new(e) as Box<dyn DataSourceRunError>),
            }
        })
    }
}

impl DataSourceRunError for GenerateCommandsError {
    fn user_facing_error(&self) -> String {
        match self {
            Self::NoProvider => NO_PROVIDER_MESSAGE,
            Self::BadPrompt => "No results found. Please try again with a more specific query.",
            Self::ProviderError => "Something went wrong. Please try again.",
        }
        .to_string()
    }

    fn telemetry_payload(&self) -> serde_json::Value {
        json!(self)
    }

    fn as_any(&self) -> &dyn Any {
        self
    }
}

mod styles {
    use crate::appearance::Appearance;

    /// The sparkle icon appears smaller than its size would indicate, so it is a bit larger than
    /// the icons used for other search result types.
    pub(super) fn icon_size(appearance: &Appearance) -> f32 {
        appearance.monospace_font_size() + 2.
    }
}
